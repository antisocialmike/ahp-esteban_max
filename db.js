async function ensureSchema() {
  if (!schemaPromise) {
    schemaPromise = isPostgres() ? ensurePostgresSchema() : ensureSqliteSchema();
  }

  return schemaPromise;
}

async function runSqliteQuery(sql, params = []) {
  const db = await getSqliteDb();
  await ensureSchema();

  if (/^\s*(BEGIN|COMMIT|ROLLBACK)/i.test(sql)) {
    await db.exec(sql);
    return [{}];
  }

  const stmt = await db.prepare(sql);
  try {
    if (isSelectLike(sql)) {
      const rows = await stmt.all(params);
      return [rows];
    }

    const result = await stmt.run(params);
    return [{ insertId: result.lastID, affectedRows: result.changes, changes: result.changes, lastID: result.lastID }];
  } finally {
    await stmt.finalize();
  }
}

async function runPostgresQuery(executor, sql, params = []) {
  await ensureSchema();

  if (/^\s*(BEGIN|COMMIT|ROLLBACK)/i.test(sql)) {
    await executor.query(sql);
    return [{}];
  }

  let translatedSql = translatePlaceholders(sql);
  const firstWord = translatedSql.trim().split(/\s+/)[0].toUpperCase();
  const needsReturning = firstWord === 'INSERT' && !/\bRETURNING\b/i.test(translatedSql);
  if (needsReturning) {
    translatedSql += ' RETURNING id';
  }

  const result = await executor.query(translatedSql, params);
  if (isSelectLike(sql)) {
    return [result.rows];
  }

  if (firstWord === 'INSERT') {
    const insertId = result.rows[0]?.id ?? null;
    return [{ insertId, affectedRows: result.rowCount, changes: result.rowCount, lastID: insertId }];
  }

  return [{ affectedRows: result.rowCount, changes: result.rowCount, rowCount: result.rowCount }];
}

async function query(sql, params = []) {
  if (isPostgres()) {
    return runPostgresQuery(getPostgresPool(), sql, params);
  }

  return runSqliteQuery(sql, params);
}

async function getConnection() {
  await ensureSchema();

  if (isPostgres()) {
    const client = await getPostgresPool().connect();
    return {
      query: (sql, params = []) => runPostgresQuery(client, sql, params),
      beginTransaction: async () => client.query('BEGIN'),
      commit: async () => client.query('COMMIT'),
      rollback: async () => client.query('ROLLBACK'),
      release: async () => client.release()
    };
  }

  const db = await getSqliteDb();
  return {
    query: runSqliteQuery,
    beginTransaction: async () => db.exec('BEGIN TRANSACTION'),
    commit: async () => db.exec('COMMIT'),
    rollback: async () => db.exec('ROLLBACK'),
    release: async () => {}
  };
}

